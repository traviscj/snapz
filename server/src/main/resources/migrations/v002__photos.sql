CREATE TABLE photos (
  id BIGINT NOT NULL AUTO_INCREMENT,
  token VARCHAR(32) NOT NULL,
  collection_id BIGINT NOT NULL,
  sha256 CHAR(64) NOT NULL,
  content_type VARCHAR(64) NOT NULL,
  bytes BIGINT NOT NULL,
  width INT NULL,
  height INT NULL,
  taken_at_ms BIGINT NOT NULL,
  note TEXT NULL,
  meta LONGTEXT NOT NULL,
  barcodes VARCHAR(1024) NULL,
  client_id VARCHAR(64) NULL,
  created_at_ms BIGINT NOT NULL,
  updated_at_ms BIGINT NOT NULL,
  deleted_at_ms BIGINT NULL,
  feed_sync_id BIGINT NULL,
  shard INT NOT NULL DEFAULT 0,
  PRIMARY KEY (id),
  UNIQUE KEY u_token (token),
  UNIQUE KEY u_client_id (client_id),
  UNIQUE KEY u_fsi (feed_sync_id),
  KEY idx_collection_taken (collection_id, taken_at_ms, id),
  KEY idx_taken (taken_at_ms, id),
  KEY idx_sha (sha256)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
